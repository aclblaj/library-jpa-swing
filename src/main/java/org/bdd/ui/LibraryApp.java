	private void showBooks(String search) {
                runDatabaseTask(() -> repository.findBooks(search), books -> {
                        DefaultTableModel model = createReadOnlyTableModel(
                                        "Title", "Author", "ISBN", "Status", "Borrowed By");
                        for (Book book : books) {
                                String status = Book.AVAILABLE.equals(book.getStatus()) ? "Available" : "Borrowed";
                                String isbn = book.getIsbn() == null ? "" : book.getIsbn();
                                String borrower = book.getBorrowedTo() == null ? "" : book.getBorrowedTo();
                                model.addRow(new Object[] { book.getTitle(), book.getAuthor(), isbn, status, borrower });
                        }
                        jTableBooks.setModel(model);
                });
	}

        private DefaultTableModel createReadOnlyTableModel(String... columnNames) {
                return new DefaultTableModel(columnNames, 0) {
                        @Override
                        public boolean isCellEditable(int row, int column) {
                                return false;
                        }
                };
        }

        private String requiredText(JTextField field, String label) {
                String value = field.getText().trim();
                if (!value.isEmpty()) {
                        return value;
                }
                showMessage(label + " is required.");
                field.requestFocusInWindow();
                return null;
        }

