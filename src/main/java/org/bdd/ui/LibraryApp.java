        private <T> void runDatabaseTask(Callable<T> operation, Consumer<T> onSuccess) {
                if (databaseBusy) {
                        return;
                }
                databaseBusy = true;
                busyGlassPane.setVisible(true);
                new SwingWorker<T, Void>() {
                        @Override
                        protected T doInBackground() throws Exception {
                                return operation.call();
                        }

                        @Override
                        protected void done() {
                                T result;
                                try {
                                        result = get();
                                } catch (InterruptedException exception) {
                                        Thread.currentThread().interrupt();
                                        setDatabaseBusy(false);
                                        showMessage("The database operation was interrupted.");
                                        return;
                                } catch (ExecutionException exception) {
                                        setDatabaseBusy(false);
                                        Throwable cause = exception.getCause();
                                        showError(cause instanceof RuntimeException runtimeException
                                                        ? runtimeException : new RuntimeException(cause));
                                        return;
                                }
                                setDatabaseBusy(false);
                                try {
                                        onSuccess.accept(result);
                                } catch (RuntimeException exception) {
                                        showError(exception);
                                }
                        }
                }.execute();
        }

        private void setDatabaseBusy(boolean busy) {
                databaseBusy = busy;
                busyGlassPane.setVisible(busy);
	}

	private void showMessage(String message) {
		JOptionPane.showMessageDialog(this, message);
	}

        private void showError(RuntimeException exception) {
		String message = exception.getMessage();
		showMessage(message == null || message.isBlank() ? "The database operation failed." : message);
	}

